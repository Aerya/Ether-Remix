package flows

import (
	"context"
	"strings"
	"testing"
	"time"

	"github.com/braedonsaunders/ether/internal/store"
)

func TestFlowsMigrationsAndCascades(t *testing.T) {
	ctx := context.Background()
	db, err := store.OpenMemory(ctx)
	if err != nil {
		t.Fatalf("OpenMemory: %v", err)
	}
	defer db.Close()

	now := time.Now().UnixMilli()
	if _, err := db.ExecContext(ctx,
		`INSERT INTO flows_definitions(id,name,graph_json,created_at_ms,updated_at_ms) VALUES(?,?,?,?,?)`,
		"flow_1", "Alert on outage", `{"schemaVersion":1,"nodes":[],"edges":[]}`, now, now,
	); err != nil {
		t.Fatalf("insert flows_definitions: %v", err)
	}
	if _, err := db.ExecContext(ctx,
		`INSERT INTO flows_runs(id,flow_id,trigger_kind,started_at_ms,updated_at_ms) VALUES(?,?,?,?,?)`,
		"run_1", "flow_1", "trigger.event", now, now,
	); err != nil {
		t.Fatalf("insert flows_runs: %v", err)
	}
	if _, err := db.ExecContext(ctx,
		`INSERT INTO flows_run_steps(run_id,seq,node_id,node_kind,status,started_at_ms) VALUES(?,?,?,?,?,?)`,
		"run_1", 1, "n1", "action", "completed", now,
	); err != nil {
		t.Fatalf("insert flows_run_steps: %v", err)
	}
	if _, err := db.ExecContext(ctx,
		`INSERT INTO flows_waiters(id,run_id,flow_id,node_id,event_type,timeout_at_ms,created_at_ms) VALUES(?,?,?,?,?,?,?)`,
		"wait_1", "run_1", "flow_1", "w1", "livetv.input.recovered", now+60000, now,
	); err != nil {
		t.Fatalf("insert flows_waiters: %v", err)
	}
	if _, err := db.ExecContext(ctx,
		`INSERT INTO flows_counters(flow_id,node_id,group_key,at_ms) VALUES(?,?,?,?)`,
		"flow_1", "win1", "title:1", now,
	); err != nil {
		t.Fatalf("insert flows_counters: %v", err)
	}
	if _, err := db.ExecContext(ctx,
		`INSERT INTO flows_dedupe(flow_id,node_id,dedupe_key,first_at_ms,last_at_ms,expires_at_ms) VALUES(?,?,?,?,?,?)`,
		"flow_1", "ded1", "k1", now, now, now+60000,
	); err != nil {
		t.Fatalf("insert flows_dedupe: %v", err)
	}
	if _, err := db.ExecContext(ctx,
		`INSERT INTO flows_schedules(flow_id,node_id,next_run_ms,last_run_ms) VALUES(?,?,?,?)`,
		"flow_1", "sched1", now+60000, 0,
	); err != nil {
		t.Fatalf("insert flows_schedules: %v", err)
	}

	// Deleting the flow cascades through runs, steps, waiters, counters, dedupe, schedules.
	if _, err := db.ExecContext(ctx, `DELETE FROM flows_definitions WHERE id=?`, "flow_1"); err != nil {
		t.Fatalf("delete flow: %v", err)
	}
	for _, tbl := range []string{"flows_runs", "flows_run_steps", "flows_waiters", "flows_counters", "flows_dedupe", "flows_schedules"} {
		var n int
		if err := db.QueryRowContext(ctx, `SELECT COUNT(*) FROM `+tbl).Scan(&n); err != nil {
			t.Fatalf("count %s: %v", tbl, err)
		}
		if n != 0 {
			t.Fatalf("%s retained %d rows after cascade delete", tbl, n)
		}
	}

	// Verify PostgreSQL DDL translation.
	pg := store.TranslateDDL(flowsMigration1)
	if strings.Contains(strings.ToUpper(pg), "AUTOINCREMENT") {
		t.Fatalf("TranslateDDL left AUTOINCREMENT in postgres DDL:\n%s", pg)
	}
	if strings.Count(pg, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY") != 2 {
		t.Fatalf("expected 2 identity PKs (flows_run_steps, flows_counters), got:\n%s", pg)
	}
}
